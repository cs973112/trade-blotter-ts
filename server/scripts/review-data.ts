/**
 * The reviewer databases: what one holds, preparing a missing one, and seeding an empty one. A
 * database is recognised by its schema, its migrations, SQLite's integrity check and its dataset's
 * identity: the version of the seed generator (DATASET_VERSION) and the SHA-256 fingerprint of
 * every trade it should hold, never by a count alone.
 *
 * A Trade Blotter database that holds anything else (an earlier version's dataset, changed trades,
 * or trades booked into the read-only benchmark) is preserved, then replaced, by step 01: its files
 * are copied byte for byte into a backup folder, the copy is opened and checked against the
 * original (SQLite's integrity check, the trade count and the fingerprint of every row), the
 * original files are checked unchanged, and only then removed. Nothing else deletes or clears a
 * database, and anything that cannot be verified that way is left as it is.
 */

export type DatasetState =
  | { readonly kind: 'missing' }
  /** A Trade Blotter database with the current schema and no trades. */
  | { readonly kind: 'empty' }
  /** Exactly the pair's dataset, then `bookings` trades booked after it (scratch only). */
  | { readonly kind: 'seeded'; readonly trades: number; readonly bookings: number }
  /** A Trade Blotter database that is behind on migrations: step 01 brings it up to date. */
  | { readonly kind: 'outdated'; readonly applied: number; readonly expected: number }
  /**
   * Anything else. `recoverable`: a Trade Blotter database (sound, with the current schema) holding
   * other trades, which step 01 may preserve and replace; its trades, counted and fingerprinted.
   */
  | { readonly kind: 'unexpected'; readonly reason: string; readonly recoverable?: { readonly trades: number; readonly fingerprint: string } }

/** The columns of the trades table, as the migrations make it; the two sort keys are generated by SQLite. */
const TRADE_COLUMNS = ['booking_sequence', 'id', 'symbol', 'side', 'quantity', 'price', 'executed_at', 'created_at', 'updated_at', 'quantity_key', 'price_key']
const STORED = 'booking_sequence, id, symbol, side, quantity, price, executed_at, created_at, updated_at'

const migrationCount = (): number => readdirSync(MIGRATIONS_FOLDER).filter((name) => /^\d{14}_/.test(name)).length

/**
 * What the pair's database holds, read through a read-only connection. Never changes the file.
 * `previous`: datasets earlier generator versions made, named as such when found.
 */
export async function inspectDataset(pair: ReviewPair, previous: typeof PREVIOUS_DATASETS = PREVIOUS_DATASETS): Promise<DatasetState> {
  if (!existsSync(pair.databasePath) || statSync(pair.databasePath).size === 0) return { kind: 'missing' }
  let client: DatabaseSync
  try {
    client = new DatabaseSync(pair.databasePath, { readOnly: true })
  } catch (error) {
    return { kind: 'unexpected', reason: `it is not a SQLite database (${error instanceof Error ? error.message : String(error)})` }
  }
  try {
    let tables: string[]
    try {
      tables = client.prepare("select name from sqlite_master where type = 'table'").all().map((row) => String(row['name']))
    } catch (error) {
      return { kind: 'unexpected', reason: `it is not a SQLite database (${error instanceof Error ? error.message : String(error)})` }
    }
    if (!tables.includes('trades') || !tables.includes('__drizzle_migrations')) {
      return { kind: 'unexpected', reason: `it is not a Trade Blotter database (tables: ${tables.join(', ') || 'none'})` }
    }
    const integrity = client.prepare('pragma integrity_check').all().map((row) => String(row['integrity_check'])).join('; ')
    if (integrity !== 'ok') return { kind: 'unexpected', reason: `SQLite's integrity check reports: ${integrity}` }
    const applied = Number(client.prepare('select count(*) as n from __drizzle_migrations').get()?.['n'] ?? 0)
    const expected = migrationCount()
    if (applied > expected) return { kind: 'unexpected', reason: `it has ${String(applied)} migrations applied, more than the ${String(expected)} this version knows` }
    if (applied < expected) return { kind: 'outdated', applied, expected }
    const columns = client.prepare('pragma table_xinfo(trades)').all().map((row) => String(row['name']))
    if (columns.join() !== TRADE_COLUMNS.join()) return { kind: 'unexpected', reason: `its trades table has the columns ${columns.join(', ')}` }

    const rows = client.prepare(`select ${STORED} from trades order by booking_sequence`).all()
    if (rows.length === 0) return { kind: 'empty' }
    const stored = rows.map(storedRow)
    const recoverable = { trades: stored.length, fingerprint: datasetFingerprint(stored) }
    const otherTrades = (reason: string): DatasetState => ({ kind: 'unexpected', reason, recoverable })
    const dataset = generateTrades(pair.count, pair.seed).map(toRow)
    const head = datasetFingerprint(stored.slice(0, dataset.length))
    if (stored.length < dataset.length || head !== datasetFingerprint(dataset)) {
      const earlier = stored.length >= dataset.length
        ? previous.find((known) => known.seed === pair.seed && known.count === dataset.length && known.fingerprint === head)
        : undefined
      const extra = stored.length - dataset.length
      if (earlier !== undefined) {
        return otherTrades(`dataset version ${String(earlier.version)}, made by an earlier seed generator${extra > 0 ? `, and ${String(extra)} more ${extra === 1 ? 'trade' : 'trades'}` : ''}; this version makes dataset version ${String(DATASET_VERSION)}`)
      }
      if (stored.length < dataset.length) return otherTrades(`${String(stored.length)} trades, fewer than the ${String(dataset.length)} of dataset version ${String(DATASET_VERSION)}`)
      const index = dataset.findIndex((want, at) => {
        const row = stored[at]
        return row === undefined || FIELDS.some((field) => row[field] !== want[field])
      })
      const want = dataset[index]
      const row = stored[index]
      const field = want === undefined || row === undefined ? 'id' : (FIELDS.find((name) => row[name] !== want[name]) ?? 'id')
      return otherTrades(`not dataset version ${String(DATASET_VERSION)}: trade ${String(index + 1)} in booking order differs (${field} is ${JSON.stringify(row?.[field])}, expected ${JSON.stringify(want?.[field])})`)
    }
    const bookings = stored.length - dataset.length
    if (bookings > 0 && !pair.bookingsAllowed) {
      return otherTrades(`dataset version ${String(DATASET_VERSION)} and ${String(bookings)} more ${bookings === 1 ? 'trade' : 'trades'}; the ${pair.label.toLowerCase()} database is only ever read`)
    }
    if (bookings > 0) {
      // Trades booked later: the application's own accounting must accept the whole history.
      try {
        summariseTrades(await createDrizzleTradeRepository(drizzle({ client })).listInTradeOrder())
      } catch (error) {
        return otherTrades(`its trades booked after seeding do not form a valid history (${error instanceof Error ? error.message : String(error)})`)
      }
    }
    return { kind: 'seeded', trades: stored.length, bookings }
  } finally {
    client.close()
  }
}

const FIELDS = ['id', 'symbol', 'side', 'quantity', 'price', 'executedAt', 'createdAt', 'updatedAt'] as const

interface StoredRow {
  readonly id: string
  readonly symbol: string
  readonly side: string
  readonly quantity: string
  readonly price: string
  readonly executedAt: string
  readonly createdAt: string
  readonly updatedAt: string
}

function storedRow(row: Record<string, unknown>): StoredRow {
  const text = (column: string): string => String(row[column])
  return {
    id: text('id'), symbol: text('symbol'), side: text('side'), quantity: text('quantity'), price: text('price'),
    executedAt: text('executed_at'), createdAt: text('created_at'), updatedAt: text('updated_at'),
  }
}

/** What to do about an unexpected database that step 01 does not replace by itself. */
export function recoveryAdvice(pair: ReviewPair, state?: DatasetState): string {
  if (state?.kind === 'unexpected' && state.recoverable !== undefined) {
    return `Run npm run review:07 to stop the reviewer applications, then npm run review:01: it preserves this database in a verified backup and replaces it.`
  }
  return [
    'Nothing was changed. It is not a Trade Blotter database the workflow can verify, so it is left to you: keep a copy if you want one, then',
    `move the file ${pair.databasePath} (and any -wal and -shm beside it) somewhere else, and run npm run review:01 and npm run review:02 again.`,
  ].join('\n')
}

/** Refuses a path that is the development database or in server/data, before anything opens it. */
export function guardPath(context: ReviewContext, pair: ReviewPair): void {
  refuseProtectedDatabase(pair.databasePath, context.protection)
}

export type PrepareOutcome =
  | { readonly kind: 'created' }
  | { readonly kind: 'migrated'; readonly from: number; readonly to: number }
  | { readonly kind: 'existing'; readonly state: DatasetState }
  /** It held other trades: preserved in a verified backup, then replaced by a new, empty database. */
  | { readonly kind: 'replaced'; readonly reason: string; readonly backup: Backup }

/** A database preserved before it was replaced. */
export interface Backup {
  readonly folder: string
  /** The database and its -wal, -shm or -journal, as they were: name and SHA-256. */
  readonly files: readonly { readonly name: string; readonly sha256: string }[]
  readonly trades: number
  /** datasetFingerprint of every trade it holds, in booking order. */
  readonly fingerprint: string
}

const SIDE_FILES = ['', '-wal', '-shm', '-journal'] as const

const sha256 = (path: string): string => createHash('sha256').update(readFileSync(path)).digest('hex')

/** The database's files that exist: the database itself, then its -wal, -shm and -journal. */
function databaseFiles(path: string): string[] {
  return SIDE_FILES.map((suffix) => `${path}${suffix}`).filter((file) => existsSync(file))
}

/** Copies a database's files, byte for byte, into a new folder; each copy is checked against its source. */
function copyDatabase(path: string, folder: string): { name: string; sha256: string }[] {
  mkdirSync(folder, { recursive: true })
  return databaseFiles(path).map((file) => {
    const copy = join(folder, basename(file))
    copyFileSync(file, copy, constants.COPYFILE_EXCL)
    const [source, copied] = [sha256(file), sha256(copy)]
    if (source !== copied) throw new Error(`The copy of ${file} differs from it (SHA-256 ${source} and ${copied}).`)
    return { name: basename(file), sha256: copied }
  })
}

/** A new folder's path for the pair's backup, named for the time, such as benchmark-20261113T043033.512Z; never one that exists. */
function newBackupFolder(context: ReviewContext, pair: ReviewPair): string {
  const base = join(context.backupsDir, `${pair.name}-${new Date().toISOString().replace(/[-:]/g, '')}`)
  let folder = base
  for (let attempt = 2; existsSync(folder); attempt++) folder = `${base}-${String(attempt)}`
  return folder
}

/**
 * Opens a second copy of a backup as SQLite would to restore it, and checks it holds exactly what
 * was read from the first: SQLite's integrity check, the trade count and every row's fingerprint.
 */
function verifyBackup(folder: string, databaseName: string, expected: { readonly trades: number; readonly fingerprint: string }): void {
  const check = join(folder, '.verify')
  try {
    mkdirSync(check)
    for (const file of databaseFiles(join(folder, databaseName))) copyFileSync(file, join(check, basename(file)))
    const client = new DatabaseSync(join(check, databaseName))
    try {
      const integrity = client.prepare('pragma integrity_check').all().map((row) => String(row['integrity_check'])).join('; ')
      if (integrity !== 'ok') throw new Error(`the backup's integrity check reports: ${integrity}`)
      const stored = client.prepare(`select ${STORED} from trades order by booking_sequence`).all().map(storedRow)
      if (stored.length !== expected.trades) throw new Error(`the backup holds ${String(stored.length)} trades, not ${String(expected.trades)}`)
      if (datasetFingerprint(stored) !== expected.fingerprint) throw new Error('the backup\'s trades differ from the database\'s')
    } finally {
      client.close()
    }
  } finally {
    rmSync(check, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 })
  }
}

/** Creates and migrates a new database at the path, as the API does at startup. */
function createDatabase(path: string): void {
  const db = openDatabase(path)
  try {
    applyMigrations(db)
  } finally {
    closeDatabase(db)
  }
}

/** Whether an application (of app:start, or of this pair) is recorded as using the database. */
function inUse(context: ReviewContext, pair: ReviewPair): DatabaseInUseError | undefined {
  try {
    refuseIfDatabaseInUse(pair.databasePath, context.protection.runDir)
    refuseIfDatabaseInUse(pair.databasePath, pair.runDir)
    return undefined
  } catch (error) {
    if (error instanceof DatabaseInUseError) return error
    throw error
  }
}

/**
 * Step 01. A missing database is created and migrated, as the API does at startup; one that is
 * behind on migrations is brought up to date the same way.
 *
 * An existing one no application uses is copied into a new backup folder first, and the copy is
 * what is inspected, so the original is never opened before it is preserved. Holding its dataset
 * (or nothing yet), it is kept and the copy discarded. Holding other trades (`recoverable`), the
 * backup is verified (verifyBackup), the original files are checked unchanged since they were
 * copied, a backup.json records what was kept and how to restore it, and only then are the
 * original files removed and a new, empty database made in their place. Anything else is only
 * reported. One in use is inspected where it is, and never replaced.
 */
export async function prepareDatabase(context: ReviewContext, pair: ReviewPair): Promise<PrepareOutcome> {
  guardPath(context, pair)
  if (!existsSync(pair.databasePath) || statSync(pair.databasePath).size === 0) {
    const busy = inUse(context, pair)
    if (busy !== undefined) throw busy
    createDatabase(pair.databasePath)
    return { kind: 'created' }
  }
  if (inUse(context, pair) !== undefined) return { kind: 'existing', state: await inspectDataset(pair) }

  const folder = newBackupFolder(context, pair)
  let keep = false
  try {
    const files = copyDatabase(pair.databasePath, folder)
    const databaseName = basename(pair.databasePath)
    const state = await inspectDataset({ ...pair, databasePath: join(folder, databaseName) })
    if (state.kind === 'outdated') {
      createDatabase(pair.databasePath)
      return { kind: 'migrated', from: state.applied, to: state.expected }
    }
    if (state.kind !== 'unexpected' || state.recoverable === undefined) return { kind: 'existing', state }

    verifyBackup(folder, databaseName, state.recoverable)
    const now = databaseFiles(pair.databasePath).map((file) => ({ name: basename(file), sha256: sha256(file) }))
    if (JSON.stringify(now) !== JSON.stringify(files)) {
      keep = true
      throw new Error(`${pair.databasePath} changed while it was being copied; nothing was removed. The copy is kept in ${folder}.`)
    }
    const backup: Backup = { folder, files, trades: state.recoverable.trades, fingerprint: state.recoverable.fingerprint }
    writeFileSync(join(folder, 'backup.json'), `${JSON.stringify({
      database: pair.databasePath, preservedAt: new Date().toISOString(), reason: state.reason,
      trades: backup.trades, tradesFingerprint: backup.fingerprint, files,
      restore: `Stop the reviewer applications (npm run review:07). Move the reviewer's ${databaseName} and any -wal and -shm beside it away, then copy ${files.map((file) => file.name).join(', ')} from this folder to ${dirname(pair.databasePath)}.`,
    }, null, 2)}\n`)
    keep = true
    for (const file of databaseFiles(pair.databasePath)) rmSync(file)
    createDatabase(pair.databasePath)
    return { kind: 'replaced', reason: state.reason, backup }
  } finally {
    if (!keep) rmSync(folder, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 })
  }
}

/**
 * Step 02: seeds the pair's dataset into an empty database with db:seed's own code, which checks
 * every trade and reads them back. Refuses unless the database is empty, and while an application
 * uses it.
 */
export async function seedPair(context: ReviewContext, pair: ReviewPair): Promise<{ readonly milliseconds: number }> {
  guardPath(context, pair)
  refuseIfDatabaseInUse(pair.databasePath, context.protection.runDir)
  const report = await seedDatabase({
    path: pair.databasePath, count: pair.count, seed: pair.seed, protection: { ...context.protection, runDir: pair.runDir },
  })
  return { milliseconds: report.milliseconds.total }
}
